def mk(id_, specialty, tema, sub, dif, age, stem, correct, wrong, bib, vars_=None, n=5):
    letters = list("ABCDE"[:n])
    d = [wrong] + BASE_D
    while len(d) < n - 1:
        d.append(d[-1] + " — inadequado neste contexto.")
    opts, i = {}, 0
    for L in letters:
        if L == "B":
            opts[L] = correct
        else:
            opts[L] = d[i]
            i += 1
    expl = correct + " Pearl: compare mecanismos, não o tamanho da opção. Distratores = erros clínicos comuns."
    if len(expl) < 110:
        expl += " Revise timing, dose e invasividade."
    return {
        "id": id_,
        "specialty": specialty,
        "tema": tema,
        "subtema": sub,
        "dificuldade": dif,
        "age": age,
        "vars": vars_ or {},
        "statement": stem,
        "options": opts,
        "correct": "B",
        "explanation": expl,
        "bibliography": bib,
    }


def emit_cjs(path, export_name, header, items, drop_specialty=False):
    arr = []
    for m in items:
        mm = dict(m)
        if drop_specialty:
            mm.pop("specialty", None)
        arr.append(mm)

    def ser(v, indent=0):
        sp = "  " * indent
        if isinstance(v, str):
            return json.dumps(v, ensure_ascii=False)
        if isinstance(v, bool):
            return "true" if v else "false"
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            return str(v)
        if v is None:
            return "null"
        if isinstance(v, list):
            return "[\n" + ",\n".join(sp + "  " + ser(x, indent + 1) for x in v) + "\n" + sp + "]"
        if isinstance(v, dict):
            return (
                "{\n"
                + ",\n".join(
                    sp
                    + "  "
                    + (k if k.isidentifier() else json.dumps(k))
                    + ": "
                    + ser(v[k], indent + 1)
                    for k in v
                )
                + "\n"
                + sp
                + "}"
            )
        return str(v)

    text = (
        f"/**\n * {header}\n */\nconst {export_name} = "
        + ser(arr)
        + f";\n\nmodule.exports = {{ {export_name} }};\n"
    )
    path.write_text(text, encoding="utf-8")
    print("wrote", path.name, len(arr))


